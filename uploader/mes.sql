-- 3공장 설비 현황 (읽기 전용). @PLANT = 3공장 PLANT_CODE (환경변수 MES_PLANT)
-- 컬럼: no, ton, status, part, mold, cav, std_ct, ct, target, prod, ng, worker, alarm, since
WITH R AS (
  SELECT *, ROW_NUMBER() OVER (PARTITION BY EQUIP_CODE ORDER BY START_DTM DESC) rn
  FROM TB_PROD_RESULT (NOLOCK) WHERE START_DT >= CONVERT(char(8), DATEADD(day,-3,GETDATE()), 112)
), N AS (
  SELECT N.*, ROW_NUMBER() OVER (PARTITION BY N.EQUIP_CODE ORDER BY N.NWRKST_DTM DESC) rn
  FROM TB_PROD_NOTWORK N (NOLOCK) WHERE N.NWRKED_DTM IS NULL AND N.NWRKST_DTM >= DATEADD(day,-3,GETDATE())
)
SELECT
  TRY_CAST(REPLACE(REPLACE(E.EQUIP_NAME,'호기',''),' ','') AS int) AS no,
  NULL AS ton,
  CASE WHEN NW.EQUIP_CODE IS NOT NULL THEN (CASE WHEN ISNULL(NC.CODE_NAME,'') LIKE '%금형%' THEN 'MOLD' WHEN ISNULL(NC.CODE_NAME,'') LIKE '%계획%' THEN 'PLAN' ELSE 'STOP' END)
       WHEN R.EQUIP_CODE IS NOT NULL AND R.END_DTM IS NULL THEN 'RUN' ELSE 'STOP' END AS status,
  ISNULL(I.ITEM_NAME,'') AS part, ISNULL(R.MOLD_CODE,'') AS mold, 1 AS cav,
  RE.APPLY_CT AS std_ct,
  CASE WHEN ISNULL(R.PROD_CNT,0) > 0 THEN CAST(DATEDIFF(second, R.START_DTM, ISNULL(R.END_DTM, GETDATE())) * 1.0 / R.PROD_CNT AS decimal(8,1)) END AS ct,
  ISNULL(O.ORDER_QTY,0) AS target, ISNULL(R.PROD_QTY,0) AS prod, ISNULL(R.BAD_QTY,0) AS ng,
  (SELECT TOP 1 U.USER_NM FROM TB_PROD_WORKMAN W (NOLOCK) JOIN TB_BASE_USER U (NOLOCK) ON U.USER_ID = W.USER_ID
     WHERE W.ORDER_NO = R.ORDER_NO AND W.SUB_ORDER = R.SUB_ORDER AND W.ROUT_SEQ = R.ROUT_SEQ AND W.WORK_SEQ = R.WORK_SEQ) AS worker,
  ISNULL(NC.CODE_NAME, NW.NWRK_CODE) AS alarm,
  ISNULL(NW.NWRKST_DTM, R.START_DTM) AS since
FROM TB_BASE_EQUIP E (NOLOCK)
LEFT JOIN R ON R.EQUIP_CODE = E.EQUIP_CODE AND R.MILL_CD = E.MILL_CD AND R.rn = 1
LEFT JOIN N NW ON NW.EQUIP_CODE = E.EQUIP_CODE AND NW.rn = 1
LEFT JOIN TB_BASE_CODE NC (NOLOCK) ON NC.SUB_CODE = NW.NWRK_CODE AND NC.MAIN_CODE IN (SELECT MAIN_CODE FROM TB_BASE_CODE WHERE REF_STR1 = 'NWRK_CODE')
LEFT JOIN TB_BASE_ITEM I (NOLOCK) ON I.MILL_CD = R.MILL_CD AND I.ITEM_CODE = R.ITEM_CODE
LEFT JOIN TB_PROD_ORDER O (NOLOCK) ON O.MILL_CD = R.MILL_CD AND O.ORDER_NO = R.ORDER_NO AND O.SUB_ORDER = R.SUB_ORDER AND O.ROUT_SEQ = R.ROUT_SEQ
LEFT JOIN TB_BASE_ROUT_EQUIP RE (NOLOCK) ON RE.ITEM_CODE = R.ITEM_CODE AND RE.EQUIP_CODE = R.EQUIP_CODE
WHERE ISNULL(E.DISUSE_DT,'') = '' AND E.PLANT_CODE = @PLANT AND E.EQUIP_GBN IN ('01','PROD_EQUIP')
